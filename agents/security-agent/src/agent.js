const fs = require("node:fs");
const path = require("node:path");
const { createPermissionContext } = require("./permissions");
const { createAuditLog } = require("./audit");
const { createTools } = require("./tools");
const { buildRemediations } = require("./remediations");

const SEVERITY_RANK = {
  CRITICAL: 5,
  ERROR: 4,
  HIGH: 4,
  MEDIUM: 3,
  WARNING: 3,
  LOW: 2,
  INFO: 1,
};

function rankFindings(findings) {
  return [...findings].sort(
    (a, b) =>
      (SEVERITY_RANK[String(b.severity).toUpperCase()] || 0) -
      (SEVERITY_RANK[String(a.severity).toUpperCase()] || 0)
  );
}

function correlate(findings) {
  const sast = findings.filter((f) => f.category === "sast");
  const sca = findings.filter((f) => f.category === "sca");
  const policy = findings.filter((f) => f.category === "policy");

  const hero =
    sast[0] ||
    sca.find((f) => /lodash/i.test(f.package || f.message || "")) ||
    sca[0] ||
    policy[0] ||
    findings[0];

  return {
    hero,
    supporting: findings.filter((f) => f !== hero).slice(0, 8),
    categories: {
      sast: sast.length,
      sca: sca.length,
      policy: policy.length,
    },
    root_cause_hypothesis: hero
      ? hero.category === "sast"
        ? "Untrusted query input concatenated into SQL (CWE-89)"
        : hero.category === "sca"
          ? `Vulnerable dependency ${hero.package || ""}@${hero.installed_version || ""}`
          : "Insecure container/policy configuration"
      : "No findings to correlate",
  };
}

function buildEvidence({
  correlation,
  plan,
  actions,
  proposed,
  validation,
  auditFile,
}) {
  const hero = correlation.hero;
  const patchList = proposed
    .map((p) => `- \`${p.outName}\` → \`${p.targetRel}\` — ${p.summary}`)
    .join("\n");

  return `# Security Agent Evidence

Generated by \`agents/security-agent\` (bounded demo workflow).

## Highest-impact issue

- **Finding ID:** ${hero ? hero.finding_id : "n/a"}
- **Tool:** ${hero ? hero.tool : "n/a"}
- **Severity:** ${hero ? hero.severity : "n/a"}
- **Location:** ${hero ? `${hero.filepath || "?"}:${hero.line || "?"}` : "n/a"}
- **Message:** ${hero ? hero.message : "n/a"}
- **Root cause hypothesis:** ${correlation.root_cause_hypothesis}

## Supporting findings

${
  correlation.supporting.length
    ? correlation.supporting
        .map(
          (f) =>
            `- \`${f.finding_id}\` (${f.tool}/${f.category}) — ${f.message}`
        )
        .join("\n")
    : "_None_"
}

## Plan

${plan.steps.map((s, i) => `${i + 1}. ${s}`).join("\n")}

## Actions taken

${actions.map((a) => `- ${a}`).join("\n")}
- Wrote audit log: \`${auditFile}\`

## Proposed remediations

${patchList || "_None_"}

${proposed
  .filter((p) => p.followUp)
  .map((p) => `> Follow-up: ${p.followUp}`)
  .join("\n")}

## Validation

${
  validation.skipped
    ? "- Unit tests skipped (\`--skip-tests\`)."
    : `- Tests exit code: **${validation.status}**\n${
        validation.status === 0
          ? "- Unit tests passed on current workspace."
          : "- Tests reported failures; do not merge without investigation."
      }`
}

## Escalate (human approval required)

The agent does **not** merge. Review the patches, re-run SAST/SCA/policy in CI, then approve the PR.

If you applied only the SQL fix, residual risk may still include dependency CVEs and Dockerfile policy failures — include those patches in the same PR or a follow-up.
`;
}

async function runAgent({
  root,
  summaryPath,
  outDir,
  allowOpenPr = false,
  applyPatch = false,
  skipTests = false,
}) {
  const perms = createPermissionContext({ allowOpenPr });
  const audit = createAuditLog(outDir);
  const tools = createTools({ root, perms, audit });

  // Observe
  audit.record({ phase: "observe", status: "start", summaryPath });
  const summary = tools.read_security_summary(summaryPath);
  const ranked = rankFindings(summary.findings || []);
  audit.record({
    phase: "observe",
    status: "ok",
    finding_count: ranked.length,
  });

  // Reason
  const correlation = correlate(ranked);
  audit.record({
    phase: "reason",
    status: "ok",
    hero: correlation.hero && correlation.hero.finding_id,
    hypothesis: correlation.root_cause_hypothesis,
    categories: correlation.categories,
  });

  // Plan + Act remediations (SQL, lodash, Dockerfile)
  const { steps, proposed, actions } = buildRemediations({
    root,
    findings: ranked,
    tools,
  });
  const plan = { steps };
  tools.write_evidence({
    outDir,
    filename: "plan.json",
    content: JSON.stringify(plan, null, 2),
  });
  audit.record({ phase: "plan", status: "ok", steps: plan.steps.length });

  // Demonstrate denied tool (talk beat)
  try {
    perms.assertTool("merge_pr");
  } catch (err) {
    audit.record({
      phase: "act",
      tool: "merge_pr",
      status: "denied",
      error: err.message,
      demo: "tool boundary",
    });
  }

  const written = [];
  for (const item of proposed) {
    const patch = tools.propose_patch({
      outDir,
      filename: item.outName,
      content: item.content,
    });
    written.push(patch.path);

    if (applyPatch) {
      const abs = path.join(root, item.targetRel);
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, item.content);
      audit.record({
        phase: "act",
        status: "applied",
        target: item.targetRel,
        kind: item.kind,
      });
    } else {
      audit.record({
        phase: "act",
        status: "proposed_only",
        target: item.targetRel,
        kind: item.kind,
        note: "Pass --apply to write into the workspace",
      });
    }
  }

  tools.write_evidence({
    outDir,
    filename: "remediations.json",
    content: JSON.stringify(
      proposed.map(({ content, ...meta }) => ({
        ...meta,
        bytes: Buffer.byteLength(content),
      })),
      null,
      2
    ),
  });

  // Validate
  let validation = { status: null, skipped: true };
  if (!skipTests) {
    validation = tools.run_tests();
    validation.skipped = false;
    audit.record({
      phase: "validate",
      status: validation.status === 0 ? "ok" : "failed",
      exit_code: validation.status,
    });
  } else {
    audit.record({ phase: "validate", status: "skipped" });
  }

  // Escalate / Present
  const evidence = buildEvidence({
    correlation,
    plan,
    actions,
    proposed,
    validation,
    auditFile: audit.file,
  });
  tools.write_evidence({
    outDir,
    filename: "evidence.md",
    content: evidence,
  });
  tools.write_evidence({
    outDir,
    filename: "correlation.json",
    content: JSON.stringify(correlation, null, 2),
  });
  audit.record({
    phase: "escalate",
    status: "human_approval_required",
    merge_permission: perms.can("OPEN_PR"),
    remediation_count: proposed.length,
  });

  return {
    outDir,
    hero: correlation.hero,
    patchPaths: written,
    auditFile: audit.file,
    validation,
    remediationCount: proposed.length,
  };
}

module.exports = { runAgent, correlate, rankFindings };
